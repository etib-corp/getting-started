plugins {
    alias(libs.plugins.android.application)
}

// Shaders and fonts of the pinned libraries. The native build copies them
// here (see cpp/CMakeLists.txt) and they are packaged as APK assets.
val engineAssetsDir = layout.buildDirectory.dir("generated/engine-assets").get().asFile

// The Python standard library and the scripts (APK assets), and the native
// libraries the standard library loads. The native build copies them here
// from the python.org package (see cmake/AndroidPython.cmake).
val pythonAssetsDir = layout.buildDirectory.dir("generated/python-assets").get().asFile
val pythonLibsDir = layout.buildDirectory.dir("generated/python-libs").get().asFile

android {
    namespace = "com.etib.getting_started"
    compileSdk = 36
    ndkVersion = "27.3.13750724"

    defaultConfig {
        applicationId = "com.etib.getting_started"
        // Android 12L, the base of the Meta Quest system software.
        minSdk = 32
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"

        ndk {
            // Meta headsets are 64-bit ARM only.
            abiFilters += listOf("arm64-v8a")
        }
        externalNativeBuild {
            cmake {
                cppFlags += "-std=c++20"
                arguments += listOf(
                    "-DANDROID_STL=c++_shared",
                    "-DANDROID_USE_LEGACY_TOOLCHAIN_FILE=OFF",
                    "-DAPP_ENGINE_ASSETS_OUTPUT_DIR=${engineAssetsDir.absolutePath}",
                    "-DAPP_PYTHON_ASSETS_OUTPUT_DIR=${pythonAssetsDir.absolutePath}",
                    "-DAPP_PYTHON_LIBS_OUTPUT_DIR=${pythonLibsDir.absolutePath}",
                )
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            // Signed with the debug key so `assembleRelease` gives an
            // installable APK. Replace with your own signing config before
            // distributing.
            signingConfig = signingConfigs.getByName("debug")
        }
    }

    externalNativeBuild {
        cmake {
            path = file("cpp/CMakeLists.txt")
            version = "3.31.5"
        }
    }

    sourceSets {
        getByName("main") {
            manifest.srcFile("AndroidManifest.xml")
            // The repository's assets/ (shared with the desktop build), then
            // the engine and Python files generated by the native build.
            assets.srcDirs("../../../assets", engineAssetsDir, pythonAssetsDir)
            jniLibs.srcDirs(pythonLibsDir)
        }
    }

    androidResources {
        // The default pattern leaves out directories whose name starts with
        // an underscore, which the Python standard library has (`_pyrepl`).
        // Every file listed in an asset manifest must be in the APK.
        ignoreAssetsPattern = "!.svn:!.git:!.ds_store:!*.scc:!CVS:!thumbs.db:!picasa.ini:!*~"
    }
}

// The engine assets, the Python assets and the Python libraries are produced
// by the native build, so it has to run before they are merged into the APK.
tasks.configureEach {
    for (kind in listOf("Assets", "JniLibFolders")) {
        if (name.startsWith("merge") && name.endsWith(kind)) {
            val variant = name.removePrefix("merge").removeSuffix(kind)
            dependsOn(tasks.matching { it.name.startsWith("buildCMake$variant") })
        }
    }
}
